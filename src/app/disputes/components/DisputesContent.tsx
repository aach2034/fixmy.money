type DisputeStatus = 'pending' | 'in_progress' | 'sent' | 'awaiting' | 'resolved' | 'rejected';
type DisputePriority = 'high' | 'medium' | 'low';

interface ClientDispute {
  id: string;
  clientId: string;
  clientName: string;
  creditorName: string;
  accountNumber: string;
  negativeItemType: string;
  bureau: string;
  disputeReason: string;
  disputeLetterTemplate: string;
  amount: number | null;
  dateReported: string;
  priority: DisputePriority;
  disputeStatus: DisputeStatus;
  responseDueDate: string;
  daysRemaining: number;
  autoGenerated: boolean;
  letterId: string | null;
  createdAt: string;
}

const bureauConfig: Record<string, { className: string }> = {
  Equifax: { className: 'bureau-eq' },
  Experian: { className: 'bureau-ex' },
  TransUnion: { className: 'bureau-tu' },
};

const priorityConfig: Record<DisputePriority, { label: string; className: string }> = {
  high: { label: 'High', className: 'bg-danger/10 text-danger border-danger/20' },
  medium: { label: 'Medium', className: 'bg-warning/10 text-warning border-warning/20' },
  low: { label: 'Low', className: 'bg-muted text-muted-foreground border-border' },
};

const itemTypeLabels: Record<string, string> = {
  collection: 'Collection',
  charge_off: 'Charge-Off',
  late_payment: 'Late Payment',
  repossession: 'Repossession',
  bankruptcy: 'Bankruptcy',
  hard_inquiry: 'Hard Inquiry',
  other: 'Other',
};

type SortField = 'clientName' | 'creditorName' | 'bureau' | 'priority' | 'daysRemaining' | 'createdAt';

function mapRow(row: any, clientMap: Record<string, string>): ClientDispute {
  const statusMap: Record<string, DisputeStatus> = {
    draft: 'pending', ready: 'pending', generated: 'in_progress', sent: 'sent',
    waiting_for_response: 'awaiting', escalated: 'in_progress', updated: 'resolved',
    deleted: 'resolved', verified: 'resolved', closed: 'resolved',
  };
  return {
    id: row.id,
    clientId: row.client_id ?? '',
    clientName: clientMap[row.client_id] ?? row.client_name ?? 'Unknown Client',
    creditorName: row.creditor_name ?? '',
    accountNumber: row.account_number_masked ?? '',
    negativeItemType: row.negative_category ?? 'other',
    bureau: row.bureau ?? 'Unknown',
    disputeReason: row.dispute_reason ?? '',
    disputeLetterTemplate: row.dispute_letter_template ?? 'FCRA Section 611',
    amount: row.balance ?? null,
    dateReported: row.date_reported
      ? new Date(row.date_reported).toLocaleDateString('en-US', { month: '2-digit', day: '2-digit', year: 'numeric' })
      : '',
    priority: (row.is_collection || row.negative_category === 'charge_off' ? 'high' : 'medium') as DisputePriority,
    disputeStatus: statusMap[row.dispute_status] ?? 'pending',
    responseDueDate: row.response_due_date
      ? new Date(row.response_due_date).toLocaleDateString('en-US', { month: '2-digit', day: '2-digit', year: 'numeric' })
      : '',
    daysRemaining: row.days_remaining ?? 30,
    autoGenerated: Boolean(row.report_id),
    letterId: row.letter_id ?? null,
    createdAt: row.created_at ?? '',
  };
}

interface DisputeDetailModal {
  dispute: ClientDispute;
  onClose: () => void;
  onGenerateLetter: (dispute: ClientDispute) => void;
  onStatusChange: (id: string, status: DisputeStatus) => void;
}

